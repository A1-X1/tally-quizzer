// Regenerate THIRD_PARTY_NOTICES.md from the licence files of everything bundled into the app.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const nm = (p) => path.join(root, 'node_modules', p)
const read = (p) => fs.readFileSync(p, 'utf8').trim()
const pkg = (p) => JSON.parse(fs.readFileSync(nm(`${p}/package.json`), 'utf8'))
const licenceFile = (p) => {
  const f = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license'].map((x) => nm(`${p}/${x}`)).find((x) => fs.existsSync(x))
  return f ? read(f) : null
}

const code = [
  ['electron', 'Application runtime. Chromium and other component licences ship inside the app as LICENSES.chromium.html.'],
  ['react', 'User interface library.'],
  ['react-dom', 'User interface library.'],
  ['scheduler', 'Dependency of React.'],
  ['katex', 'Maths typesetting, including the KaTeX fonts.'],
  ['better-sqlite3', 'SQLite bindings. SQLite itself is in the public domain.'],
  ['zod', 'Input validation.'],
  ['unpdf', 'Reading text from PDF study material. Bundles PDF.js by Mozilla (Apache License 2.0).'],
  ['mammoth', 'Reading text from Word (.docx) study material.'],
  ['jszip', 'Reading PowerPoint (.pptx) files. Used under the MIT licence option.']
]
const fonts = [
  ['@fontsource-variable/bricolage-grotesque', 'Bricolage Grotesque', 'Display type'],
  ['@fontsource-variable/instrument-sans', 'Instrument Sans', 'Text type'],
  ['@fontsource-variable/spline-sans-mono', 'Spline Sans Mono', 'Figures and data']
]

let out = `# Third-party notices

Tally bundles the software and fonts listed below. Each is used under the licence shown.
This file is generated by \`node scripts/notices.mjs\`.

## Fonts

All three fonts are distributed under the SIL Open Font License, Version 1.1. The full licence text follows the list.

| Font | Use | Version | Copyright |
|---|---|---|---|
`
for (const [p, name, use] of fonts) {
  const first = (licenceFile(p) ?? '').split('\n')[0].replace(/ \S+\.ttf:.*$/, '')
  out += `| ${name} | ${use} | ${pkg(p).version} | ${first} |\n`
}
const ofl = licenceFile(fonts[0][0]) ?? ''
out += `\n<details><summary>SIL Open Font License 1.1</summary>\n\n\`\`\`text\n${ofl.slice(ofl.indexOf('This Font Software'))}\n\`\`\`\n\n</details>\n\n## Software\n\n`
for (const [p, note] of code) {
  const info = pkg(p)
  out += `### ${p} ${info.version}\n\n${note} Licence: ${info.license}.\n\n\`\`\`text\n${licenceFile(p) ?? `${info.license} licence`}\n\`\`\`\n\n`
}
out += `### SQLite

SQLite is in the public domain: https://www.sqlite.org/copyright.html
`
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out)
console.log('THIRD_PARTY_NOTICES.md written')
